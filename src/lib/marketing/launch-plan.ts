const START = "2026-11-25";

/** Pacific standard time all through the plan (DST ended Nov 1), so -08:00. */
export function planTime(day: number, platform: PlatformId): string {
  const [y, m, d] = START.split("-").map(Number);
  const date = new Date(Date.UTC(y, m - 1, d + day));
  const ymd = date.toISOString().slice(0, 10);
  return new Date(`${ymd}T${POST_TIME[platform]}:00-08:00`).toISOString();
}

